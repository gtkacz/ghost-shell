"""Rasterises Natural Earth 1:50m land into the uplink globe's land mask, and writes the land bit of each of the globe's
dots to lib/landbits.mjs, which the globe's shader reads. The shell never loads the mask.

usage:
    uv run --no-project --with pyshp --with pillow --with numpy python -I scripts/land-mask.py \
        --mask <mask.png> --bits <landbits.mjs>
    uv run --no-project --with pyshp --with pillow --with numpy python -I scripts/land-mask.py \
        --check <mask.png> <landbits.mjs>

The first downloads the archive into a new temporary directory and checks its SHA-256. --check needs no network.
"""

import argparse
import hashlib
import math
import re
import sys
import tempfile
import urllib.request
import zipfile
from pathlib import Path

import numpy as np
import shapefile
from PIL import Image, ImageDraw

ARCHIVE_URL = "https://naciscdn.org/naturalearth/50m/physical/ne_50m_land.zip"
# Fetched 2026-10-22 (Natural Earth 4.1.0's land). A new release changes the mask, so it has to be a deliberate edit.
ARCHIVE_SHA256 = "0b8e670cf80dce9cbebe2a193bc44ba5602758c22e1fa603980553646d7ff162"
SHAPE_MEMBERS = ("ne_50m_land.shp", "ne_50m_land.shx", "ne_50m_land.dbf")
DOWNLOAD_TIMEOUT_S = 60

# Equirectangular, 180° W at the left and 90° N at the top.
MASK_WIDTH = 2048
MASK_HEIGHT = 1024
LAND = 1
SEA = 0
# Pillow puts pixel n's centre at coordinate n, while texel n spans n to n + 1 here, so the polygons move half a texel
# up and left for each texel to be judged at its centre.
PILLOW_CENTRE_SHIFT = 0.5

# The reference mockup's dot lattice, which lib/globe.mjs draws: y = 1 - 2i/(N - 1), longitude i golden angles.
LATTICE_POINTS = 3200
GOLDEN_ANGLE = math.pi * (3 - math.sqrt(5))

# As globe.frag unpacks them: bit k of component c is dot 24c + k, four components a word. A float holds an integer
# below 2^24 exactly, so a component takes 24 bits.
BITS_PER_COMPONENT = 24
COMPONENTS_PER_WORD = 4
LAND_WORDS = math.ceil(LATTICE_POINTS / (BITS_PER_COMPONENT * COMPONENTS_PER_WORD))

HEADER = "// Generated by scripts/land-mask.py from widgets/uplink/land-mask.png. Do not edit."
WORD_LINE = re.compile(r"^  \[(\d+), (\d+), (\d+), (\d+)\],$")
POINTS_LINE = f"export const LAND_BIT_POINTS = {LATTICE_POINTS};"

# The plan's checks: São Paulo, London and central Australia are land; just south-east of São Paulo, the mid-Atlantic
# and the mid-North-Atlantic are sea.
LAND_POINTS = ((-23.55, -46.63), (51.5, -0.12), (-25.0, 135.0))
SEA_POINTS = ((-25.0, -44.5), (0.0, -30.0), (35.0, -40.0))


def fetch_shapes(directory: Path) -> shapefile.Reader:
    archive = directory / "ne_50m_land.zip"
    with urllib.request.urlopen(ARCHIVE_URL, timeout=DOWNLOAD_TIMEOUT_S) as response:
        archive.write_bytes(response.read())
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    if digest != ARCHIVE_SHA256:
        sys.exit(f"{ARCHIVE_URL}: SHA-256 {digest}, expected {ARCHIVE_SHA256}")
    with zipfile.ZipFile(archive) as bundle:
        for member in SHAPE_MEMBERS:
            (directory / member).write_bytes(bundle.read(member))
    return shapefile.Reader(str(directory / SHAPE_MEMBERS[0]))


def to_mask(lon: float, lat: float) -> tuple[float, float]:
    x = (lon + 180) / 360 * MASK_WIDTH - PILLOW_CENTRE_SHIFT
    y = (90 - lat) / 180 * MASK_HEIGHT - PILLOW_CENTRE_SHIFT
    return (x, y)


def signed_area(ring: list[tuple[float, float]]) -> float:
    return sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(ring, ring[1:] + ring[:1])) / 2


def rings(shape: shapefile.Shape) -> list[list[tuple[float, float]]]:
    bounds = list(shape.parts) + [len(shape.points)]
    return [[tuple(point) for point in shape.points[start:end]] for start, end in zip(bounds, bounds[1:])]


def rasterise(shapes: shapefile.Reader) -> Image.Image:
    mask = Image.new("1", (MASK_WIDTH, MASK_HEIGHT), SEA)
    for shape in shapes.iterShapes():
        # Shapefile outer rings run clockwise and holes (lakes such as the Caspian) anticlockwise. Each polygon is
        # drawn on its own and then added, so that one polygon's hole never erases another polygon's island.
        polygon = Image.new("1", mask.size, SEA)
        draw = ImageDraw.Draw(polygon)
        for ring in rings(shape):
            fill = LAND if signed_area(ring) < 0 else SEA
            draw.polygon([to_mask(lon, lat) for lon, lat in ring], fill=fill)
        mask.paste(LAND, mask=polygon)
    return mask


def texel(lat: float, lon: float) -> tuple[int, int]:
    # The south pole and 180° E sit on the far edges, one texel past the last.
    column = min(MASK_WIDTH - 1, math.floor((lon + 180) / 360 * MASK_WIDTH))
    row = min(MASK_HEIGHT - 1, math.floor((90 - lat) / 180 * MASK_HEIGHT))
    return (column, row)


def land_at(pixels: np.ndarray, lat: float, lon: float) -> bool:
    column, row = texel(lat, lon)
    return bool(pixels[row, column])


def lattice_point(i: int) -> tuple[float, float]:
    y = 1 - 2 * i / (LATTICE_POINTS - 1)
    theta = GOLDEN_ANGLE * i
    lat = math.degrees(math.asin(y))
    lon = math.degrees(math.atan2(math.sin(theta), math.cos(theta)))
    return (lat, lon)


def land_bits(pixels: np.ndarray) -> list[bool]:
    return [land_at(pixels, *lattice_point(i)) for i in range(LATTICE_POINTS)]


def pack(bits: list[bool]) -> list[list[int]]:
    components = [0] * (LAND_WORDS * COMPONENTS_PER_WORD)
    for i, bit in enumerate(bits):
        if bit:
            components[i // BITS_PER_COMPONENT] |= 1 << (i % BITS_PER_COMPONENT)
    return [components[at:at + COMPONENTS_PER_WORD] for at in range(0, len(components), COMPONENTS_PER_WORD)]


def module_text(words: list[list[int]]) -> str:
    lines = [HEADER, POINTS_LINE, "export const LAND_WORDS = ["]
    lines += [f"  [{', '.join(str(component) for component in word)}]," for word in words]
    lines.append("];")
    return "\n".join(lines) + "\n"


def mask_pixels(path: Path) -> np.ndarray:
    image = Image.open(path)
    if image.size != (MASK_WIDTH, MASK_HEIGHT) or image.mode != "1":
        sys.exit(f"{path}: {image.size[0]} x {image.size[1]} mode {image.mode}, expected {MASK_WIDTH} x {MASK_HEIGHT} 1-bit")
    return np.asarray(image, dtype=bool)


def parse_words(path: Path) -> list[list[int]]:
    lines = path.read_text().splitlines()
    if lines[:3] != [HEADER, POINTS_LINE, "export const LAND_WORDS = ["] or lines[-1] != "];":
        sys.exit(f"{path}: not the module this script writes")
    words = []
    for line in lines[3:-1]:
        match = WORD_LINE.match(line)
        if not match:
            sys.exit(f"{path}: not a word line: {line!r}")
        words.append([int(component) for component in match.groups()])
    return words


def check(mask_path: Path, bits_path: Path) -> None:
    pixels = mask_pixels(mask_path)
    for points, expected, name in ((LAND_POINTS, True, "land"), (SEA_POINTS, False, "sea")):
        for lat, lon in points:
            if land_at(pixels, lat, lon) != expected:
                sys.exit(f"{mask_path}: ({lat}, {lon}) should be {name}")
            print(f"{name} ({lat}, {lon})")
    words = parse_words(bits_path)
    if len(words) != LAND_WORDS:
        sys.exit(f"{bits_path}: {len(words)} words, expected {LAND_WORDS}")
    limit = 1 << BITS_PER_COMPONENT
    if any(component >= limit for word in words for component in word):
        sys.exit(f"{bits_path}: a component is not below 2^{BITS_PER_COMPONENT}")
    expected = pack(land_bits(pixels))
    if words != expected:
        components = [component for word in words for component in word]
        wanted = [component for word in expected for component in word]
        first = next(at for at, (got, want) in enumerate(zip(components, wanted)) if got != want)
        sys.exit(f"{bits_path}: component {first} is {components[first]}, the mask gives {wanted[first]}")
    print("ok")


def main(argv: list[str]) -> None:
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("--mask", type=Path)
    parser.add_argument("--bits", type=Path)
    parser.add_argument("--check", nargs=2, type=Path, metavar=("MASK", "BITS"))
    args = parser.parse_args(argv)
    if args.check:
        check(*args.check)
        return
    if not args.mask or not args.bits:
        parser.error("give --mask and --bits, or --check")
    with tempfile.TemporaryDirectory(prefix="land-mask.") as directory:
        mask = rasterise(fetch_shapes(Path(directory)))
    mask.save(args.mask, optimize=True)
    args.bits.write_text(module_text(pack(land_bits(mask_pixels(args.mask)))))


if __name__ == "__main__":
    main(sys.argv[1:])
